export async function cleanupPendingProductImageAction(
  imagePath: string
): Promise<ActionState> {
  const trimmedPath = imagePath.trim();
  if (!trimmedPath) {
    return { error: "Falta la ruta de imagen." };
  }

  const adminContext = await requireAdminPermission("manageProducts");
  try {
    if (
      !isOwnedProductImagePath(trimmedPath, adminContext.businessId, {
        requireCanonicalProductFolder: true
      })
    ) {
      return { error: "La imagen no pertenece a este negocio." };
    }

    const supabase = await createSupabaseServerClient();
    const status = await removeProductImageIfUnreferenced({
      supabase,
      businessId: adminContext.businessId,
      imageUrlOrPath: trimmedPath
    });

    if (status === "failed") {
      logActionFailure("products.cleanupPendingImage", new Error(status), {
        businessId: adminContext.businessId
      });
      return { error: "No pudimos limpiar la imagen temporal." };
    }

    return { success: true };
  } catch (error) {
    logActionFailure("products.cleanupPendingImage", error, {
      businessId: adminContext.businessId
    });
    return {
      error: getActionErrorMessage(error, "No pudimos limpiar la imagen temporal.")
    };
  }
}

export async function createProductAction(
  _prevState: ActionState,
  formData: FormData
) {
  const productId = getTrimmedString(formData.get("product_id"));
  const name = getTrimmedString(formData.get("name"));
  const price = getPriceValue(formData.get("price"));
  const description = getOptionalTrimmedString(formData.get("description"));
  const categoryId = getTrimmedString(formData.get("category_id"));
  const imageIntent = parseProductImageIntent(formData.get("image_intent"), [
    "none",
    "replace"
  ]);
  const imagePath = getOptionalTrimmedString(formData.get("image_path"));
  const sku = formData.get("sku")?.toString().trim() || null;
  const stockStr = formData.get("stock")?.toString();
  const stock = stockStr ? parseInt(stockStr, 10) : 0;
  const trackStock = formData.get("track_stock") === "on";

  if (!productId || !isCanonicalProductUuid(productId)) {
    return { error: "Identificador de producto inválido." };
  }

  if (!name) {
    return { error: "Ingresa un nombre para el producto." };
  }

  if (price === null) {
    return { error: "Ingresa un precio valido." };
  }

  if (!categoryId) {
    return { error: "Selecciona una categoria." };
  }

  if (!Number.isFinite(stock) || stock < 0) {
    return { error: "Ingresa un stock valido." };
  }

  if (!imageIntent) {
    return { error: "La intención de imagen no es válida." };
  }

  const adminContext = await requireAdminPermission("manageProducts");
  try {
    const supabase = await createSupabaseServerClient();

    const categoryValidationError = await validateCategoryOwnership({
      supabase,
      businessId: adminContext.businessId,
      categoryId
    });

    if (categoryValidationError) {
      return { error: categoryValidationError };
    }

    let resolvedImageUrl: string | null = null;

    if (imageIntent === "replace") {
      if (
        !imagePath ||
        !isOwnedProductImagePath(imagePath, adminContext.businessId, {
          requireCanonicalProductFolder: true
        })
      ) {
        return { error: "La imagen del producto no es válida." };
      }

      const pathParts = imagePath.split("/");
      if (pathParts[1] !== productId) {
        return { error: "La imagen del producto no es válida." };
      }

      resolvedImageUrl = getCanonicalProductImagePublicUrl(supabase, imagePath);
    }

    const effectiveIsAvailable = resolveEffectiveProductAvailability({
      trackStock,
      stock,
      requestedAvailable: true
    });

    const insertPayloadBase = {
      id: productId,
      business_id: adminContext.businessId,
      name,
      price,
      category_id: categoryId,
      description,
      image_url: resolvedImageUrl,
      is_available: effectiveIsAvailable,
      stock,
      track_stock: trackStock
    };

    if (sku) {
      const { error } = await supabase.from("products").insert({
        ...insertPayloadBase,
        sku
      });

      if (error) {
        if (isProductSkuUniqueViolation(error)) {
          return { error: PRODUCT_SKU_DUPLICATE_USER_ERROR };
        }

        throw new Error("No pudimos crear el producto.");
      }
    } else {
      const autoSkuPrefix = await resolveAutoSkuPrefixForCategory({
        supabase,
        businessId: adminContext.businessId,
        categoryId
      });

      if (autoSkuPrefix.error || !autoSkuPrefix.prefix) {
        return {
          error: autoSkuPrefix.error ?? "No pudimos generar el SKU automaticamente."
        };
      }

      let inserted = false;

      for (let attempt = 1; attempt <= PRODUCT_SKU_AUTO_GENERATE_RETRY_LIMIT; attempt += 1) {
        const candidateSku = await resolveNextAutoGeneratedSku({
          supabase,
          businessId: adminContext.businessId,
          prefix: autoSkuPrefix.prefix
        });

        if (candidateSku.error || !candidateSku.sku) {
          return {
            error: candidateSku.error ?? "No pudimos generar el SKU automaticamente."
          };
        }

        const { error } = await supabase.from("products").insert({
          ...insertPayloadBase,
          sku: candidateSku.sku
        });

        if (!error) {
          inserted = true;
          break;
        }

        if (isProductSkuUniqueViolation(error)) {
          continue;
        }

        throw new Error("No pudimos crear el producto.");
      }

      if (!inserted) {
        return { error: PRODUCT_SKU_AUTO_GENERATE_EXHAUSTED_USER_ERROR };
      }
    }

    revalidatePath("/admin/products");
    revalidatePublicCatalogCache({
      businessId: adminContext.businessId,
      slug: adminContext.businessSlug,
      scope: "catalog"
    });
    return { success: true };
  } catch (error) {
    logActionFailure("products.create", error, { categoryId, productId });
    return { error: getActionErrorMessage(error, "No pudimos crear el producto.") };
  }
}

export async function setProductAvailabilityAction(
  productId: string,
  isAvailable: boolean
): Promise<ActionState> {
  if (!productId) {
    return { error: "Falta identificar el producto." };
  }

  const adminContext = await requireAdminPermission("manageProducts");
  try {
    const supabase = await createSupabaseServerClient();

    const { data: currentProduct, error: currentProductError } = await supabase
      .from("products")
      .select("id, stock, track_stock, archived_at")
      .eq("id", productId)
      .eq("business_id", adminContext.businessId)
      .maybeSingle();

    if (currentProductError) {
      throw new Error("No pudimos cargar el producto.");
    }

    if (!currentProduct) {
      return { error: "Este producto ya no existe o pertenece a otro negocio." };
    }

    if (currentProduct.archived_at != null) {
      return {
        error: "El producto está archivado. Restáuralo para editarlo."
      };
    }

    if (
      isAvailable &&
      currentProduct.track_stock === true &&
      (currentProduct.stock ?? 0) <= 0
    ) {
      return { error: TRACKED_ZERO_STOCK_ENABLE_ERROR };
    }

    const { error } = await supabase
      .from("products")
      .update({ is_available: isAvailable })
      .eq("id", productId)
      .eq("business_id", adminContext.businessId);

    if (error) {
      throw new Error("No pudimos actualizar la disponibilidad del producto.");
    }

    revalidatePath("/admin/products");
    revalidatePublicCatalogCache({
      businessId: adminContext.businessId,
      slug: adminContext.businessSlug,
      scope: "catalog"
    });
    return { success: true };
  } catch (error) {
    logActionFailure("products.setAvailability", error, { productId, isAvailable });
    return {
      error: getActionErrorMessage(error, "No pudimos actualizar la disponibilidad del producto.")
    };
  }
}

