export async function archiveProductAction(
  productId: string
): Promise<LifecycleActionState> {
  if (!productId || !isCanonicalProductUuid(productId)) {
    return { error: "Falta identificar el producto." };
  }

  const adminContext = await requireAdminPermission("manageProducts");
  try {
    const supabase = await createSupabaseServerClient();

    const { data: currentProduct, error: currentProductError } = await supabase
      .from("products")
      .select("id, archived_at")
      .eq("id", productId)
      .eq("business_id", adminContext.businessId)
      .maybeSingle();

    if (currentProductError) {
      throw new Error("No pudimos cargar el producto.");
    }

    if (!currentProduct) {
      return { error: "El producto ya está archivado o ya no está disponible." };
    }

    if (currentProduct.archived_at != null) {
      return { error: "El producto ya está archivado o ya no está disponible." };
    }

    const { data: updatedRows, error } = await supabase
      .from("products")
      .update({
        archived_at: new Date().toISOString(),
        is_available: false
      })
      .eq("id", productId)
      .eq("business_id", adminContext.businessId)
      .is("archived_at", null)
      .select("id");

    if (error) {
      throw new Error("No pudimos archivar el producto.");
    }

    if (!updatedRows || updatedRows.length === 0) {
      return { error: "El producto ya está archivado o ya no está disponible." };
    }

    revalidateProductLifecycleCaches({
      businessId: adminContext.businessId,
      businessSlug: adminContext.businessSlug
    });
    return { success: true };
  } catch (error) {
    logActionFailure("products.archive", error, { productId });
    return {
      error: getActionErrorMessage(
        error,
        "No pudimos completar la acción. Intentá nuevamente."
      )
    };
  }
}

